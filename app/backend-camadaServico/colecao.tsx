export function getSignoAtual(data: Date): Signo {
  const mesAtual = data.getMonth() + 1;
  const diaAtual = data.getDate();
  const dataAtualValor = mesAtual * 100 + diaAtual;

  const signoAtual =
    dadosSignos.find((signo) => {
      const inicioValor = signo.inicio.mes * 100 + signo.inicio.dia;
      const fimValor = signo.fim.mes * 100 + signo.fim.dia;

      if (inicioValor > fimValor) {
        return dataAtualValor >= inicioValor || dataAtualValor <= fimValor;
      }

      return dataAtualValor >= inicioValor && dataAtualValor <= fimValor;
    }) ?? dadosSignos[0];

  return signoAtual;
}

export function getFraseDoDia(signo: Signo, data: Date): string {
  const indiceFrase = (data.getDate() - 1) % signo.frases.length;
  return signo.frases[indiceFrase];
}